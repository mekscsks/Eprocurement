      <li>Submitted by the end-users after the approval of the GAA</li>
      <li>Separate form for NCSE and Infrastructure Projects</li>
      <li>Submitted to the Government Procurement Policy Board – January of the succeeding year</li>
    </ul>
  </div>

  <!-- Supplemental PPMP -->
  <div class="section">
    <h3>Supplemental PPMP</h3>
    <ul>
      <li>Items to be procured that are not included in the Final PPMP</li>
      <li>Separate form for NCSE and Infrastructure Projects</li>
      <li>Submitted as needed within the FY</li>
    </ul>
  </div>

  <!-- PPMP Preparation -->
  <div class="section">
    <h3>PPMP Preparation</h3>
    <p>With the returned LIB and the list of suggested modes from the UP Procurement Office, the Administrative Officer shall prepare the PPMP or supplemental PPMP, whichever is applicable.</p>
    <h4>Reminders:</h4>
    <ul>
      <li>Use the required format (which will be provided by the UP Procurement Office)</li>
      <li>Identify specific items to be procured; items or services not covered by R.A. No. 9184 shall not be included in the PPMP or the supplemental PPMP</li>
      <li>Identify the timeline for the items to be procured</li>
      <li>Indicate the budget. Budget must be within the approved LIB or IOB</li>
      <li>The prepared PPMP shall be reviewed and approved by the Head of College or Office</li>
      <li>Once signed and approved, the PPMP or the supplemental PPMP shall be submitted to the UP Procurement Office ()</li>
    </ul>
  </div>
