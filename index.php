<script>

  // Bidding filter
  var currentFilter = 'all';
  function setFilter(btn, status) {
    currentFilter = status;
    document.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    filterBids();
  }
  function filterBids() {
    var query = document.getElementById('bidSearchInput').value.toLowerCase();
    var rows = document.querySelectorAll('#bidTable tbody tr');
    var visible = 0;
    rows.forEach(function(row) {
      var matchStatus = currentFilter === 'all' || row.dataset.status === currentFilter;
      var matchSearch = query === '' || row.textContent.toLowerCase().includes(query);
      row.style.display = (matchStatus && matchSearch) ? '' : 'none';
      if (matchStatus && matchSearch) visible++;
    });
    document.getElementById('bidCount').textContent = 'Showing ' + visible + ' of ' + rows.length + ' opportunities';
  }

    // FAQ accordion
  document.querySelectorAll('.faq-q').forEach(q => {
    q.addEventListener('click', () => {
      const item = q.closest('.faq-item');
      const isOpen = item.classList.contains('open');
      document.querySelectorAll('.faq-item').forEach(i => i.classList.remove('open'));
      if (!isOpen) item.classList.add('open');
    });
  });

  // Toast
  (function() {
    var box = document.getElementById('toastBox');
    var close = document.getElementById('toastClose');
    var timer;
    setTimeout(function() { box.classList.add('show'); timer = setTimeout(function(){ box.classList.remove('show'); }, 7000); }, 800);
    close.addEventListener('click', function() { box.classList.remove('show'); clearTimeout(timer); });
  })();
</script>

